import test from "node:test";
import assert from "node:assert/strict";
import {createGame,isValidSave,stepGame,pcCount} from "../dist/js/sim/engine.js";
import {recordPaidSession,recordStationMinute,stationAccountingSummary,validStationLedger} from "../dist/js/sim/stationAccounting.js";
import {serializeSave,parseImportedSave} from "../dist/js/sim/saveTransfer.js";
import {buyComputer} from "../dist/js/sim/shop.js";
import {expandShop} from "../dist/js/sim/economy.js";

test("sessões VIP e rateio energético não alteram o caixa",()=>{
 const s=createGame(5);
 assert.equal(s.stationLedger,undefined);
 const before=[s.cash,s.revenue,s.expenses,s.energyAccrued];
 recordPaidSession(s,1,3,15,true);
 recordPaidSession(s,0,3,10,false);
 s.customers=[{id:1,x:0,y:0,target:{x:0,y:0},stage:"using",costume:"regular",pcIndex:1,usedMinutes:0,waitingMinutes:0,offlineWait:0,happy:true}];
 recordStationMinute(s,3,.6);
 assert.deepEqual([s.cash,s.revenue,s.expenses,s.energyAccrued],before);
 assert.deepEqual(s.stationLedger.map(x=>x.sessions),[1,1,0]);
 assert.equal(s.stationLedger[1].vipSessions,1);
 assert.equal(s.stationLedger[1].vipRevenue,15);
 assert.equal(s.stationLedger[1].occupiedMinutes,1);
 assert.equal(s.stationLedger[0].occupiedMinutes,0);
 assert.ok(Math.abs(s.stationLedger.reduce((a,r)=>a+r.energyShare,0)-.6)<1e-12);
 const restored=parseImportedSave(serializeSave(s));
 assert.deepEqual(restored.stationLedger,s.stationLedger);
});
test("saves legados permanecem válidos e os dados inválidos são recusados",()=>{
 const s=createGame(8);
 assert.equal(isValidSave(s),true);
 assert.equal(validStationLedger(undefined),true);
 assert.equal(validStationLedger([{sessions:1,vipSessions:2,sessionRevenue:10,vipRevenue:10,occupiedMinutes:1,energyShare:1}]),false);
 assert.equal(validStationLedger([{sessions:-1,vipSessions:0,sessionRevenue:0,vipRevenue:0,occupiedMinutes:0,energyShare:0}]),false);
 s.stationLedger=[{sessions:0,vipSessions:0,sessionRevenue:0,vipRevenue:0,occupiedMinutes:0,energyShare:NaN}];
 assert.equal(isValidSave(s),false);
 delete s.stationLedger;
 assert.equal(parseImportedSave(serializeSave(s)).stationLedger,undefined);
 assert.equal(stationAccountingSummary(s,0).sessions,0);
});
test("inserir PC original mantém históricos dos anexos nos índices corretos",()=>{
 const s=createGame(13);
 s.cash=5000;
 s.roomExtensions={west:1,east:0,south:0,north:0};
 s.annexPcs=[{slotId:"pc-west-1"}];
 recordPaidSession(s,3,4,44,true);
 s.pcGpus=[null,null,null,"gpu09"];
 assert.equal(expandShop(s).ok,true);
 assert.equal(buyComputer(s).ok,true);
 assert.equal(pcCount(s),5);
 assert.equal(s.stationLedger[3].sessions,0);
 assert.equal(s.stationLedger[4].sessionRevenue,44);
 assert.equal(s.pcGpus[4],"gpu09");
 assert.equal(s.stationLedger.length,pcCount(s));
 assert.equal(isValidSave(s),true);
});
test("cinco dias no motor: sessões e rateio conferem com receita e energia",()=>{
 const s=createGame(23);
 for(let d=0;d<5;d++)for(let i=0;i<6;i++)stepGame(s,120);
 assert.equal(s.totalMinutes,5*720);
 assert.equal(s.stationLedger.length,pcCount(s));
 assert.ok(s.served>0);
 const visits=s.stationLedger.reduce((sum,x)=>sum+x.sessions,0);
 const gross=s.stationLedger.reduce((sum,x)=>sum+x.sessionRevenue,0);
 const energy=s.stationLedger.reduce((sum,x)=>sum+x.energyShare,0);
 assert.equal(visits,s.served);
 assert.ok(gross>0&&gross<=s.revenue);
 assert.ok(Math.abs(energy-s.energyAccrued)<1e-8);
 assert.equal(s.cash,850+s.revenue-s.expenses);
 assert.deepEqual(parseImportedSave(serializeSave(s)).stationLedger,s.stationLedger);
});
