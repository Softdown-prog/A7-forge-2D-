test("nível máximo e cronograma impedem melhoria antecipada de internet",()=>{
 const s=createGame(7003,"historical"),port=createCommerceNetworkPort(()=>s);
 s.cash=5000;
 assert.equal(gameYear(s),1998);
 let view=port.snapshot();
 assert.equal(view.internetStatus,"Discada · Nível 1 · Online");
 assert.equal(view.internetUpgradeDisabled,true);
 assert.equal(view.internetUpgradeLabel,"Via rádio · 🔒 Disponível em 2002");
 s.totalMinutes=4*360*720;
 view=port.snapshot();
 assert.equal(view.internetUpgradeDisabled,false);
 assert.equal(view.internetUpgradeLabel,"Via rádio · R$ 250");
 s.internetTier=2;
 view=port.snapshot();
 assert.equal(view.internetUpgradeDisabled,true);
 assert.equal(view.internetUpgradeLabel,"Fibra óptica · 🔒 Disponível em 2007");
 s.totalMinutes=9*360*720;
 view=port.snapshot();
 assert.equal(view.internetUpgradeDisabled,false);
 assert.equal(view.internetUpgradeLabel,"Fibra óptica · R$ 500");
 s.cash=499;
 assert.equal(port.snapshot().internetUpgradeDisabled,true);
 s.cash=500;s.internetTier=3;
 view=port.snapshot();
 assert.equal(view.internetUpgradeDisabled,true);
 assert.equal(view.internetUpgradeLabel,"Internet no nível máximo");
 assert.equal(view.internetStatus,INTERNET_ERAS[2].name+" · Nível 3 · Online");
});
test("falha e reparo mostram atraso e preço do técnico sem realizar ação",()=>{
 const s=createGame(7004,"classic"),port=createCommerceNetworkPort(()=>s);
 const before=JSON.stringify(s);
 let view=port.snapshot();
 assert.equal(view.internetRepairDisabled,true);
 assert.equal(view.internetRepairLabel,"Chamar técnico · R$ 75");
 s.offlineUntil=s.totalMinutes+43;
 view=port.snapshot();
 assert.equal(view.internetRepairDisabled,false);
 assert.equal(view.internetStatus,"Discada · Nível 1 · Sem conexão até 43 min de jogo");
 s.internetTier=3;
 view=port.snapshot();
 assert.equal(view.internetRepairLabel,"Chamar técnico · R$ 125");
 assert.equal(view.internetStatus,"Fibra óptica · Nível 3 · Sem conexão até 43 min de jogo");
 assert.notEqual(JSON.stringify(s),before);
 assert.equal(s.offlineUntil,s.totalMinutes+43);
});
