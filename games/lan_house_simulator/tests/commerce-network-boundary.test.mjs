test("troca de save mantém porta ligada à partida nova e conserva a antiga",()=>{
 let s=createGame(7006,"historical");
 const port=createCommerceNetworkPort(()=>s),prior=s,previous=JSON.stringify(prior);
 s=parseImportedSave(serializeSave(s));
 s.supplierTier=2;s.offlineUntil=s.totalMinutes+19;
 assert.equal(isValidSave(s),true);
 const view=port.snapshot();
 assert.equal(view.supplierUpgradeDisabled,true);
 assert.equal(view.internetRepairDisabled,false);
 assert.ok(view.internetStatus.endsWith("19 min de jogo"));
 assert.equal(JSON.stringify(prior),previous);
});
test("renderizador atualiza botões existentes sem trocar handlers ou foco",()=>{
 const s=createGame(7007,"historical"),port=createCommerceNetworkPort(()=>s);
 const ids=["supplier-up","internet-up","internet-repair"];
 const nodes=new Map(ids.map(id=>["#"+id,{id,disabled:false,textContent:"",listeners:["click"]}]));
 const doc={querySelector:selector=>nodes.get(selector)??null};
 const textValues=new Map(),setText=(id,value)=>textValues.set(id,value);
 renderCommerceNetworkPanel(port.snapshot(),setText,doc);
 assert.deepEqual([...textValues.keys()],["supplier-status","stock-soda","stock-candy","stock-snacks","internet"]);
 assert.equal(nodes.get("#internet-up").disabled,true);
 assert.equal(nodes.get("#internet-repair").disabled,true);
 const original=nodes.get("#internet-up");
 s.totalMinutes=4*360*720;s.cash=1000;s.offlineUntil=s.totalMinutes+8;
 renderCommerceNetworkPanel(port.snapshot(),setText,doc);
 assert.equal(nodes.get("#internet-up"),original);
 assert.equal(nodes.get("#internet-up").listeners[0],"click");
 assert.equal(nodes.get("#internet-up").disabled,false);
 assert.equal(nodes.get("#internet-repair").disabled,false);
 assert.equal(nodes.get("#internet-up").textContent,"Via rádio · R$ 250");
 assert.equal(textValues.get("internet"),"Discada · Nível 1 · Sem conexão até 8 min de jogo");
});
test("camadas seguem independentes e main não calcula fornecedor ou upgrade",()=>{
 const root=new URL("../src/",import.meta.url);
 const app=readFileSync(new URL("application/commerceNetworkPort.ts",root),"utf8");
 const ui=readFileSync(new URL("ui/commerceNetworkPanel.ts",root),"utf8");
 assert.doesNotMatch(app,/\b(document|window|HTMLElement|HTMLButtonElement)\b/);
 assert.doesNotMatch(ui,/from\s*["']\.\.\/sim\//);
 assert.doesNotMatch(ui,/\bGameState\b|addEventListener|replaceChildren|innerHTML/);
 assert.ok(sourceModule("application/gamePorts.ts").includes("createCommerceNetworkPort(getState)"));
 assert.ok(sourceModule("ui/gamePanels.ts").includes("renderCommerceNetworkPanel(commerceNetworkPort.snapshot(),setText,document)"));
 assertCompositionAdaptersExclude(/\bwholesaleCost\(|\bsupplierLevel\(/);
 assertSourceCall("ui/runtimeControls.ts","installServiceControls",["ports.serviceActions"]);
});
