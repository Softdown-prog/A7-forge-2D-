import test from "node:test";
import assert from "node:assert/strict";
import {createGame,stepGame} from "../dist/js/sim/engine.js";
import {actorStyleFor} from "../dist/js/render/actorArt.js";
import {serializeSave,parseImportedSave} from "../dist/js/sim/saveTransfer.js";

test("female visitor has a separate, stable visual identity",()=>{
 const female=actorStyleFor("female",3);
 assert.notDeepEqual(female,actorStyleFor("regular",3));
 assert.equal(female.hair,actorStyleFor("female",210).hair);
});
test("female visitors enter the original customer flow and survive saving",()=>{
 const s=createGame(13);s.reputation=100;s.pricePerHour=1;
 let found=false;
 for(let i=0;i<600&&!found;i++){
  stepGame(s,1);
  found=s.customers.some(c=>c.costume==="female");
 }
 assert.ok(found,"the newcomer must be generated by normal arrivals");
 const saved=parseImportedSave(serializeSave(s));
 assert.ok(saved.customers.some(c=>c.costume==="female"));
 assert.equal(saved.rng,s.rng);
});
